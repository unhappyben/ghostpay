// one-shot generator: builds vendor/poseidon13.mjs from the locally installed
// poseidon-lite@0.3.0 constants (t=2 for poseidon1, t=4 for poseidon3), reusing
// the exact permutation code from vendor/poseidon2.mjs. Run: node gen-poseidon13.mjs
import { createRequire } from 'module';
import { readFileSync, writeFileSync } from 'fs';

const require = createRequire(import.meta.url);
// exports map hides ./constants/*, so require by absolute path
const plDir = new URL('./node_modules/poseidon-lite/constants/', import.meta.url);
const c1 = require(plDir.pathname + '1.js').default;
const c3 = require(plDir.pathname + '3.js').default;

// take the shared permutation body verbatim from vendor/poseidon2.mjs so the
// two files can never drift apart algorithmically.
const src = readFileSync(new URL('./vendor/poseidon2.mjs', import.meta.url), 'utf8');
const from = src.indexOf('// unstringifyBigInts');
const to = src.indexOf('const C2 = unstringifyBigInts(PARAMS);');
if (from < 0 || to < 0) throw new Error('could not slice permutation from vendor/poseidon2.mjs');
const body = src.slice(from, to);

const out = `// poseidon1 + poseidon3 — vendored ESM port of poseidon-lite@0.3.0 (MIT,
// https://github.com/vimwitch/poseidon-lite), for the Privacy Pools withdrawal
// path (spentNullifierHash = poseidon1, commitment = poseidon3). Constants are
// byte-identical to poseidon-lite/constants/1.js and constants/3.js; the
// permutation is copied verbatim from vendor/poseidon2.mjs.
// Generated by gen-poseidon13.mjs; verified against poseidon-lite in test-commitment.mjs.
const PARAMS1 = ${JSON.stringify(c1)};
const PARAMS3 = ${JSON.stringify(c3)};

${body}const C1 = unstringifyBigInts(PARAMS1);
const C3 = unstringifyBigInts(PARAMS3);
export function poseidon1(inputs, nOuts) {
  return poseidon(inputs, C1, nOuts);
}
export function poseidon3(inputs, nOuts) {
  return poseidon(inputs, C3, nOuts);
}
`;
writeFileSync(new URL('./vendor/poseidon13.mjs', import.meta.url), out);
console.log('wrote vendor/poseidon13.mjs');
